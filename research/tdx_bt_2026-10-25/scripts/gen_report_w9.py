# -*- coding: utf-8 -*-
"""把 scan100.json + 行业映射 生成为结题报告 md（表格由数据生成，不手抄）。"""
import json, os, sys

ROOT = r"D:\DeepQuant power by txm\DeepQuant-main"
RD = os.path.join(ROOT, "research", "tdx_bt_2026-10-25")

IND = {
    "002756": "有色金属", "002416": "商贸零售", "601717": "机械设备", "002572": "轻工制造",
    "600273": "基础化工", "000157": "机械设备", "002540": "有色金属", "600057": "交通运输",
    "600096": "基础化工", "002601": "基础化工", "600997": "煤炭", "603706": "公用事业",
    "600737": "农林牧渔", "601019": "传媒", "002737": "医药生物", "600282": "钢铁",
    "600729": "商贸零售",
}
BUCKETS = ["远低于均线", "低于均线", "均线附近", "高于均线", "远高于均线"]


def pct(v, d=1):
    return "-" if v is None else f"{v*100:+.{d}f}%"


def main():
    d = json.load(open(os.path.join(RD, "pool", "scan100.json"), encoding="utf-8"))
    rows = d["rows"]
    for r in rows:
        r["ind"] = IND.get(r["code"], "")

    low = [r for r in rows if r["bucket"] == "远低于均线"]
    w_low = sum(r["weight"] for r in low)
    L = []
    A = L.append

    A("# 中证红利 100 只成分股「现价 / MA12 − 1」状态扫描（2026-10-23）")
    A("")
    A("> 结题报告｜产物目录 `research/tdx_bt_2026-10-25/`｜脚本 `scripts/scan_pool100.py`")
    A("> 数据源：通达信 MCP（`tdx_kline`, period=4 日线 700 根 / period=6 月线 260 根, **tqFlag=2 后复权**）")
    A(f"> 有效样本 {d['n']}/100（缺失 {len(d['missing'])}）｜日线源 {sum(1 for r in rows if r['src']=='D')} 只、月线源 {sum(1 for r in rows if r['src']=='M')} 只")
    A("")
    A("## 1. 结论先行")
    A("")
    A(f"**当前处于「远低于均线」（现价/MA12 − 1 < −8%）的有 {len(low)} 只，合计占指数权重 {w_low:.2f}%。**")
    A("")
    A("这是 100 只成分股里唯一一档在历史上被验证过有正期望的状态。按 `bt_current_state.py` 在")
    A("2007-2026 共 227 个月上的分档统计，该档（全池等权层面，n=26）后续 12 个月收益中位 **+28.99%**、")
    A("亏损概率仅 **19%**，是全部分档里唯一「高收益 + 低亏损概率」的组合。")
    A("")
    A("但必须同时说清三件事，否则这个名单会被误用：")
    A("")
    A("1. **分档统计是「全池等权」层面的，不是「单只股票」层面的。** 历史 n=26 说的是「整个池子跌到 −8% 以下之后」，")
    A("   不是「某只票跌到 −8% 以下之后」。把它套到个股上是**跨层推断**，本文不能提供个股层的胜率证据。")
    A("2. **历史上「远低于均线」这一档在 2008/2015 那种崩塌里出现过，而你明确说过只做短窗口、不扛多年。**")
    A("   所以这份名单的用法应是「买一段就卖」，不是「越跌越买、长期持有」。")
    A("3. **−8% 是价/均线的位置，不是估值。** 一只票可以因为基本面恶化而长期贴在均线下方，")
    A("   这类「价值陷阱」在下面的「近 1 年 + 窗口回撤」两列里有迹可循。")
    A("")
    A("## 2. 名单：17 只「远低于均线」")
    A("")
    A("按 state 从低到高排（越低＝离 12 月均线越远）。`state稳` 是分档依据：MA12 只取**已完结**的 12 个月末；")
    A("`state含` 把 2026-10 这个未完结月也算进去，用来看口径敏感度。")
    A("")
    A("| # | 代码 | 名称 | 行业 | 权重% | 现价 | state稳 | state含 | 不复权 | 窗口回撤 | 窗口收益 | 近1年 |")
    A("|---:|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for i, r in enumerate(low, 1):
        px = f"{r['raw_close']:.2f}" if r["raw_close"] else "-"
        A(f"| {i} | {r['code']} | {r['name'].replace(' ','')} | {r['ind']} | {r['weight']:.2f} | {px} "
          f"| **{pct(r['state_excl'],2)}** | {pct(r['state_incl'],2)} | {pct(r['state_raw'],1)} "
          f"| {pct(r['mdd_win'])} | {pct(r['ret_win'])} | {pct(r['ret_1y'])} |")
    A("")
    A(f"合计权重 **{w_low:.2f}%**；覆盖 **{len(set(r['ind'] for r in low))} 个申万一级行业**"
      f"（基础化工 3 只、有色金属 2、机械设备 2、商贸零售 2，其余各 1）。")
    A("")
    A("### 2.1 行业分布")
    A("")
    from collections import Counter
    c = Counter(r["ind"] for r in low)
    A("| 行业 | 只数 | 合计权重% |")
    A("|---|---:|---:|")
    for k, v in c.most_common():
        A(f"| {k} | {v} | {sum(x['weight'] for x in low if x['ind']==k):.2f} |")
    A("")
    A("## 3. 全部 100 只分档")
    A("")
    A("| 分档 | 区间 | 只数 | 合计权重% |")
    A("|---|---|---:|---:|")
    rg = {"远低于均线": "< −8%", "低于均线": "−8% ~ −2%", "均线附近": "−2% ~ +2%",
          "高于均线": "+2% ~ +8%", "远高于均线": "> +8%"}
    for b in BUCKETS:
        g = [r for r in rows if r["bucket"] == b]
        A(f"| {b} | {rg[b]} | {len(g)} | {sum(x['weight'] for x in g):.2f} |")
    A("")
    dn = [r for r in rows if r['state_excl'] < 0]
    up = [r for r in rows if r['state_excl'] >= 0]
    A("分布**按只数左偏、按权重右偏**，这两个方向相反，必须分开说：")
    A("")
    A("| 口径 | 均线下方 | 均线上方 |")
    A("|---|---|---|")
    A(f"| 只数 | {len(dn)} 只 | {len(up)} 只 |")
    A(f"| 合计权重 | {sum(r['weight'] for r in dn):.2f}% | {sum(r['weight'] for r in up):.2f}% |")
    A("")
    A("也就是说：**跌离均线的票更多（46 vs 32），但更重的那批（银行、能源、交运）还在均线上方**。")
    A("所以「中证红利整体在均线下方」只在等权口径成立；按指数权重加权，它其实在均线上方。")
    A("这一点直接决定用法：**买这份名单等于主动低配指数的大权重成分**，会偏离指数。")
    A("")
    A("## 4. 方法学：为什么推翻本地数据湖，全部改走通达信")
    A("")
    A("第一版扫描用的是本地 `data/qfq_all`（自算 ADJ，覆盖 99/100，一次算完、零 token）。")
    A("做跨源验证时发现它不可用：")
    A("")
    A("| 检查 | 结果 |")
    A("|---|---|")
    A("| MA12 窗口内两源价格形状最大相对偏离 | **36.50%**（002572 索菲亚，2026-05→06：TDX −11.9% vs qfq −21.3%） |")
    A("| 该偏离的中位数（44 只可比） | **6.87pp** |")
    A("| 原因 | 自算 ADJ 的送股/转增 RATIO 被重复计入（`MEMORY.md` §6 记载过的「两个 RATIO 同值相加会翻倍」） |")
    A("")
    A("**结论：`data/qfq_all` 不能用于本题**，与预登记 `crosscheck_qfq_tdx.json`（A/B/C 三判据 FAIL）的结论一致。")
    A("全部改为逐只拉通达信后复权序列（日线 88 只 + 月线 12 只，共 148 次调用，全部落盘、零 token 损耗）。")
    A("")
    A("### 4.1 两个必须先钉死的前提，都做了独立验证")
    A("")
    A("**(a) 日线与月线的后复权在月末是否一致？** —— 一致，逐位相同。")
    A("对 31 只同时有日线 + 月线的股票，在 36 个重叠月份上比对月末收盘价，")
    A("**最大相对差 0.000%**；state 也完全相同（如 601699 两条路径都是 −1.30%）。")
    A("所以 12 只用月线的股票（含 600096 云天化）与 88 只用日线的可以放在同一张表里。")
    A("")
    A("**(b) 为什么必须用后复权、不能用不复权？** —— 因为红利股股息率 5~7%，不复权会在除权日凭空「跌」5%。")
    A("17 只名单股逐个对照（同一数据源、同一末日、只是复权方式不同）：")
    A("**1+state_不复权 < 1+state_后复权 对全部 17 只都成立**（如 002756 后复权 −29.75% vs 不复权 −36.49%）。")
    A("即不复权会**系统性夸大**「跌离均线」的幅度，把本来只是除权的票误判成超跌。")
    A("这条不等式本身是可证的：后复权因子只增不减，故 `mean(不复权)/P_now` 被系统性抬高。")
    A("反过来，凡是违反这条不等式的记录，就一定不是不复权（实测混进了前复权）——脚本用它做过滤器，剔除了 3 条污染记录。")
    A("")
    A("### 4.2 口径敏感度")
    A("")
    A("- **含未完结月 vs 只取已完结月**：13 只在两者间跳档（重百集团 −7.57%→−9.13% 跨过 −8% 线；")
    A("  藏格矿业 −8.56%→−7.39% 反向跨过）。名单因此对「要不要把 10 月这 3 周算进 MA12」敏感，")
    A("  本文统一采用「只取已完结 12 个月」作为分档依据，理由是它不被当月未走完的行情扭曲。")
    A("- **历史分位**：只有 36 只有 2009 年前起的长月线，其余无法算自身历史分位。")
    A("  17 只名单里只有 3 只有分位（中联重科 18%、云天化 19%），且都处于自身历史的低分位区，")
    A("  与「远低于均线」方向一致；其余 14 只这一列留空，**不用 NULL 冒充数据**。")
    A("")
    A("## 5. 这份名单能干什么、不能干什么")
    A("")
    A("**能做**：作为 2023-01 起短窗口口径下的候选池。你拍板过「回撤上限 20%」「接受的回撤内跑赢且年化>3」，")
    A("下一步应把这份名单按等权或按权重建组合，用同一套短窗口回测引擎跑，看能不能在 20% 回撤内拿到年化 >3%。")
    A("")
    A("**不能做**：")
    A("- 不能把「历史全池该档 +28.99%」直接当成这 17 只个股的预期收益（跨层推断）。")
    A("- 不能用「不复权跌得多」来加仓——那 5% 是除权，钱没少。")
    A("- 不能因为名单分散在 13 个行业就认为风险分散了：**N_eff 只测线性相关，测不到尾部同时性**，")
    A("  而这 17 只里有 3 只是基础化工（同一商品价格链）。")
    A("")
    A("## 6. 复现")
    A("")
    A("```")
    A("cd research/tdx_bt_2026-10-25")
    A("C:/Users/77436/.workbuddy/binaries/python/envs/dq_clean/Scripts/python.exe scripts/scan_pool100.py")
    A("```")
    A("")
    A("产物：`pool/scan100.json`（100 只全字段）、`pool/monthly_coverage.json`、`pool/daily_need.json`、`pool/need_final.json`")
    A("")
    A("---")
    A("")
    A("## 附：全部 100 只明细")
    A("")
    A("| 代码 | 名称 | 权重% | 现价 | state稳 | state含 | 分档 | 窗口回撤 | 窗口收益 | 近1年 |")
    A("|---|---|---:|---:|---:|---:|---|---:|---:|---:|")
    for r in rows:
        px = f"{r['raw_close']:.2f}" if r["raw_close"] else "-"
        A(f"| {r['code']} | {r['name'].replace(' ','')} | {r['weight']:.2f} | {px} "
          f"| {pct(r['state_excl'],2)} | {pct(r['state_incl'],2)} | {r['bucket']} "
          f"| {pct(r['mdd_win'])} | {pct(r['ret_win'])} | {pct(r['ret_1y'])} |")
    A("")

    out = os.path.join(ROOT, "docs", "TDX_W9_POOL100_SCAN_2026-10-25.md")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))
    print("written", out, os.path.getsize(out), "bytes")
    print(f"远低于均线 {len(low)} 只，权重 {w_low:.2f}%")


if __name__ == "__main__":
    main()
